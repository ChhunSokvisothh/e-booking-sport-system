-- ============================================================
-- E-Booking Sport System - Supabase Database Setup
-- ============================================================
-- Purpose:
-- This single file lets your friend recreate the Supabase database
-- structure used by your booking app.
--
-- How to use (walkthrough):
-- 1) Open Supabase project dashboard.
-- 2) Go to SQL Editor -> New query.
-- 3) Paste this whole file and run it once.
-- 4) Verify tables in Table Editor:
--    - public.core_facility
--    - public.core_timeslot
--    - public.core_booking
-- 5) (Optional) Keep only timeslot + booking if facility data stays in Django.
-- 6) In your Django .env set:
--    SUPABASE_BOOKING_TABLE=core_booking
--    SUPABASE_TIMESLOT_TABLE=core_timeslot
--
-- Notes:
-- - Your backend uses SERVICE ROLE KEY for Supabase access.
-- - For this demo, Row Level Security (RLS) is disabled to avoid policy errors.
-- - If you enable RLS later, add proper policies first.
-- ============================================================

begin;

-- Optional extension (useful if you later add UUID keys).
create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- 1) Facilities (matches Django Facility model)
-- ------------------------------------------------------------
create table if not exists public.core_facility (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    sport_type varchar(32) not null,
    is_indoor boolean not null default false,
    description text not null default '',
    location_name varchar(255) not null,
    latitude double precision not null default 11.5564,
    longitude double precision not null default 104.9282,
    base_price_per_hour numeric(10,2) not null,
    rating numeric(2,1) not null default 4.5,
    image_url text,
    owner_user_id uuid,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint chk_core_facility_sport_type
        check (sport_type in (
            'football','billiard','pickleball','volleyball',
            'basketball','futsal','tennis','badminton'
        )),
    constraint chk_core_facility_rating
        check (rating >= 0 and rating <= 5)
);

create index if not exists idx_core_facility_sport_indoor_active
    on public.core_facility (sport_type, is_indoor, is_active);

-- ------------------------------------------------------------
-- 2) Timeslots (main live slot table read by backend from Supabase)
-- ------------------------------------------------------------
create table if not exists public.core_timeslot (
    id bigint generated by default as identity primary key,
    facility_id bigint not null,
    start_at timestamptz not null,
    end_at timestamptz not null,
    max_bookings integer not null default 1,
    current_bookings integer not null default 0,
    is_open boolean not null default true,
    availability_state varchar(12) not null default 'available',
    availability_updated_at timestamptz not null default now(),
    reservation_hold_until timestamptz,
    slot_version integer not null default 1,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint fk_core_timeslot_facility
        foreign key (facility_id) references public.core_facility(id) on delete cascade,
    constraint chk_core_timeslot_time_range
        check (end_at > start_at),
    constraint chk_core_timeslot_capacity
        check (max_bookings >= 0 and current_bookings >= 0 and current_bookings <= max_bookings),
    constraint chk_core_timeslot_state
        check (availability_state in ('available', 'full', 'closed')),
    constraint uq_core_timeslot_facility_window
        unique (facility_id, start_at, end_at)
);

create index if not exists idx_core_timeslot_facility_start
    on public.core_timeslot (facility_id, start_at);

create index if not exists idx_core_timeslot_start_end
    on public.core_timeslot (start_at, end_at);

create index if not exists idx_core_timeslot_open_state_start
    on public.core_timeslot (is_open, availability_state, start_at);

-- ------------------------------------------------------------
-- 3) Bookings (updated by mock payment endpoint via Supabase upsert)
-- ------------------------------------------------------------
create table if not exists public.core_booking (
    id bigint primary key,
    status varchar(20) not null default 'pending',
    payment_status varchar(20) not null default 'mock_pending',
    facility_id bigint,
    time_slot_id bigint,
    user_id text,
    booking_source varchar(20) not null default 'manual',
    chatbot_session_id varchar(64) not null default '',
    updated_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    constraint chk_core_booking_status
        check (status in ('pending', 'confirmed', 'cancelled', 'rescheduled')),
    constraint chk_core_booking_payment_status
        check (payment_status in ('mock_pending', 'mock_paid', 'mock_failed')),
    constraint chk_core_booking_source
        check (booking_source in ('manual', 'chatbot')),
    constraint fk_core_booking_facility
        foreign key (facility_id) references public.core_facility(id) on delete set null,
    constraint fk_core_booking_time_slot
        foreign key (time_slot_id) references public.core_timeslot(id) on delete set null
);

create index if not exists idx_core_booking_status_payment
    on public.core_booking (status, payment_status);

create index if not exists idx_core_booking_source_session
    on public.core_booking (booking_source, chatbot_session_id);

create index if not exists idx_core_booking_user_id_updated
    on public.core_booking (user_id, updated_at desc);

-- ------------------------------------------------------------
-- 4) Trigger to auto-update updated_at on each write
-- ------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_core_facility_updated_at on public.core_facility;
create trigger trg_core_facility_updated_at
before update on public.core_facility
for each row execute function public.set_updated_at();

drop trigger if exists trg_core_timeslot_updated_at on public.core_timeslot;
create trigger trg_core_timeslot_updated_at
before update on public.core_timeslot
for each row execute function public.set_updated_at();

drop trigger if exists trg_core_booking_updated_at on public.core_booking;
create trigger trg_core_booking_updated_at
before update on public.core_booking
for each row execute function public.set_updated_at();

-- ------------------------------------------------------------
-- 5) RLS (disabled for backend service-role demo setup)
-- ------------------------------------------------------------
alter table public.core_facility disable row level security;
alter table public.core_timeslot disable row level security;
alter table public.core_booking disable row level security;

